-- SkillTree initial schema.
-- ${json_type} is a Flyway placeholder: jsonb on PostgreSQL, character varying on H2 (local dev/tests).

create table users (
    id            bigint generated by default as identity primary key,
    email         varchar(255) not null unique,
    password_hash varchar(100) not null,
    display_name  varchar(100),
    role          varchar(20)  not null,
    created_at    timestamp with time zone not null
);

-- Headless CMS: one row per content item (skill template, theme, app config).
-- "content" is the working copy; the live version is the revision referenced by published_revision.
create table cms_entries (
    id                 bigint generated by default as identity primary key,
    type               varchar(30)  not null,
    slug               varchar(80)  not null,
    status             varchar(20)  not null,
    content            ${json_type} not null,
    current_revision   integer      not null,
    published_revision integer,
    updated_by         bigint references users (id),
    created_at         timestamp with time zone not null,
    updated_at         timestamp with time zone not null,
    constraint uq_cms_entries_type_slug unique (type, slug)
);

create table cms_revisions (
    id         bigint generated by default as identity primary key,
    entry_id   bigint       not null references cms_entries (id) on delete cascade,
    revision   integer      not null,
    content    ${json_type} not null,
    note       varchar(500),
    created_by bigint references users (id),
    created_at timestamp with time zone not null,
    constraint uq_cms_revisions_entry_revision unique (entry_id, revision)
);

-- Immutable snapshots that mobile clients download. Rollback = new version with an old payload.
create table app_config_versions (
    id             bigint generated by default as identity primary key,
    version        integer      not null unique,
    schema_version integer      not null,
    payload        ${json_type} not null,
    checksum       varchar(64)  not null,
    source         varchar(20)  not null,
    note           varchar(500),
    created_by     bigint references users (id),
    created_at     timestamp with time zone not null
);

create table admin_audit_logs (
    id          bigint generated by default as identity primary key,
    actor_id    bigint references users (id),
    actor_email varchar(255),
    action      varchar(50) not null,
    target_type varchar(30),
    target_id   varchar(80),
    details     ${json_type},
    created_at  timestamp with time zone not null
);
create index ix_audit_created_at on admin_audit_logs (created_at);

-- User-owned skill trees (manual, from template, or AI generated).
create table skill_trees (
    id            uuid primary key,
    owner_id      bigint       not null references users (id) on delete cascade,
    title         varchar(120) not null,
    description   varchar(1000),
    source        varchar(20)  not null,
    template_slug varchar(80),
    nodes         ${json_type} not null,
    created_at    timestamp with time zone not null,
    updated_at    timestamp with time zone not null
);
create index ix_skill_trees_owner on skill_trees (owner_id);

create table ai_generation_logs (
    id            bigint generated by default as identity primary key,
    user_id       bigint       not null references users (id) on delete cascade,
    topic         varchar(200) not null,
    status        varchar(20)  not null,
    model         varchar(60),
    input_tokens  integer,
    output_tokens integer,
    created_at    timestamp with time zone not null
);
create index ix_ai_logs_user_created on ai_generation_logs (user_id, created_at);
