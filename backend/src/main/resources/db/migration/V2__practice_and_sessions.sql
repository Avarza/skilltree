-- Practice content per skill node (AI generated once, then served from cache).
create table node_practice (
    id          bigint generated by default as identity primary key,
    tree_id     uuid         not null references skill_trees (id) on delete cascade,
    node_id     varchar(40)  not null,
    content     ${json_type} not null,
    model       varchar(60),
    created_at  timestamp with time zone not null,
    constraint uq_node_practice unique (tree_id, node_id)
);

-- Focused study time, feeds the weekly study chart and streaks.
create table study_sessions (
    id               bigint generated by default as identity primary key,
    user_id          bigint      not null references users (id) on delete cascade,
    tree_id          uuid        not null references skill_trees (id) on delete cascade,
    node_id          varchar(40) not null,
    duration_seconds integer     not null,
    ended_at         timestamp with time zone not null
);
create index ix_study_sessions_user_ended on study_sessions (user_id, ended_at);
